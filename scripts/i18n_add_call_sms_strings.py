    path = f"scripts/i18n/{module}_strings.json"
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    for locale, values in new_entries.items():
        bucket = data.setdefault(locale, {})
        for key, value in values.items():
            bucket.setdefault(key, value)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(f"{module}: ensured {len(new_entries[''])} keys x {len(new_entries)} locales")
